import { Link, useParams } from 'react-router-dom';
import {
  AlertTriangle,
  BrainCircuit,
  CheckCircle2,
  CloudOff,
  FileWarning,
  ShieldCheck,
  Upload,
} from 'lucide-react';
import { CaseWorkspaceLayout } from '../components/case/CaseWorkspaceLayout';
import { Badge, Button, Card, ErrorState, Spinner } from '../components/common';
import { useCaseDetails } from '../hooks/useCaseDetails';
import { useDocuments } from '../hooks/useDocuments';
import { MVP_ISSUE_CATEGORIES } from '../utils/constants';
import { getCategoryLabel } from '../utils/formatters';

export function CaseAnalysisPage() {
  const { id: caseId } = useParams();
  const { caseData, loading, error, refreshCase } = useCaseDetails(caseId);
  const { documents } = useDocuments(caseId);

  return (
    <CaseWorkspaceLayout
      title="AI Case Analysis"
      caseData={caseData}
      actions={
        <Link to={`/case/${caseId}/evidence`}>
          <Button variant="secondary" size="sm" icon={Upload}>
            Add Documents ({documents.length})
          </Button>
        </Link>
      }
    >
      {loading && <Spinner centered label="Loading case intelligence structure..." />}

      {!loading && error && (
        <ErrorState
          title="Unable to load case details"
          description={error}
          onRetry={refreshCase}
        />
      )}

      {!loading && !error && caseData && (
        <div className="gs-stack-lg">
          {/* Honest Integration Status */}
          <div className="gs-banner gs-banner-warning">
            <CloudOff size={18} style={{ flexShrink: 0, marginTop: 2 }} />
            <div>
              <strong>AI Analysis Not Connected (Waiting for AI Integration):</strong> This
              frontend-only MVP displays the prepared intelligence layout. Automated extraction,
              cross-document checks, and findings will populate once the Python FastAPI AI service
              is connected.
            </div>
          </div>

          {/* Local Case Context Ready for Future AI */}
          <Card
            title="Submitted Case Input Ready for Future Analysis"
            subtitle="Actual user-entered facts stored locally in your browser"
            action={<Badge tone="info">{documents.length} Local Document(s)</Badge>}
          >
            <div className="gs-grid-2">
              <div>
                <span className="gs-text-xs gs-muted">Selected Dispute Category</span>
                <div style={{ fontWeight: 600 }}>
                  {getCategoryLabel(caseData.category, MVP_ISSUE_CATEGORIES)}
                </div>
              </div>
              <div>
                <span className="gs-text-xs gs-muted">Timeline Events Recorded</span>
                <div style={{ fontWeight: 600 }}>
                  {(caseData.timelineEvents || []).length} user-entered event(s)
                </div>
              </div>
            </div>
          </Card>

          {/* Prepared Structured Sections */}
          <div className="gs-grid-2">
            <Card
              title="1. Identified Issue"
              action={<Badge tone="neutral">Pending AI</Badge>}
            >
              <div style={{ display: 'flex', gap: 10, alignItems: 'flex-start' }}>
                <BrainCircuit size={18} color="var(--color-text-muted)" style={{ marginTop: 2 }} />
                <p className="gs-text-sm gs-muted">
                  No analysis available yet. Once connected, the AI service will classify and
                  summarize the core consumer dispute from your inputs.
                </p>
              </div>
            </Card>

            <Card
              title="2. Confidence &amp; Verification Information"
              action={<Badge tone="neutral">Unverified</Badge>}
            >
              <div style={{ display: 'flex', gap: 10, alignItems: 'flex-start' }}>
                <ShieldCheck size={18} color="var(--color-text-muted)" style={{ marginTop: 2 }} />
                <p className="gs-text-sm gs-muted">
                  Verification status and confidence indicators will be shown here only when
                  generated by the backend AI pipeline.
                </p>
              </div>
            </Card>

            <Card title="3. Extracted Facts">
              <p className="gs-text-sm gs-muted">
                Waiting for AI integration — extracted dates, invoice amounts, and order identifiers
                will appear here after document processing.
              </p>
            </Card>

            <Card title="4. Evidence Observations">
              <div style={{ display: 'flex', gap: 10, alignItems: 'flex-start' }}>
                <CheckCircle2 size={17} color="var(--color-text-muted)" style={{ marginTop: 2 }} />
                <p className="gs-text-sm gs-muted">
                  No AI observations available yet for your {documents.length} locally saved
                  document(s).
                </p>
              </div>
            </Card>

            <Card title="5. Missing Evidence">
              <div style={{ display: 'flex', gap: 10, alignItems: 'flex-start' }}>
                <FileWarning size={17} color="var(--color-text-muted)" style={{ marginTop: 2 }} />
                <p className="gs-text-sm gs-muted">
                  Recommendations on missing receipts, warranty cards, or chat proofs will appear
                  after AI review.
                </p>
              </div>
            </Card>

            <Card title="6. Possible Inconsistencies">
              <div style={{ display: 'flex', gap: 10, alignItems: 'flex-start' }}>
                <AlertTriangle size={17} color="var(--color-text-muted)" style={{ marginTop: 2 }} />
                <p className="gs-text-sm gs-muted">
                  Waiting for AI integration — potential date or statement mismatches will be
                  flagged here with explanations.
                </p>
              </div>
            </Card>
          </div>

          <Card
            title="7. Important Findings"
            subtitle="Structured findings with supporting evidence and official references"
          >
            <p className="gs-text-sm gs-muted">
              No AI findings generated yet. Automated legal or factual findings are intentionally
              disabled in this frontend-only build.
            </p>
          </Card>
        </div>
      )}
    </CaseWorkspaceLayout>
  );
}
